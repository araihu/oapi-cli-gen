package generator

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"strconv"
	"strings"

	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"golang.org/x/tools/imports"
)

func renderCommands(options Options, operations []codegen.OperationDefinition, sdkImports []*ast.ImportSpec) ([]byte, error) {
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by oapi-cli-gen. DO NOT EDIT.\npackage cli\nimport (\n \"bytes\"\n \"net/http\"\n \"github.com/spf13/cobra\"\n %q\n %q\n", options.Module+"/internal/api", options.Module+"/internal/cliruntime")
	for _, im := range sdkImports {
		path, _ := strconv.Unquote(im.Path.Value)
		if path == "bytes" || path == "net/http" {
			continue
		}
		alias := ""
		if im.Name != nil {
			alias = im.Name.Name
		}
		fmt.Fprintf(&out, "%s %q\n", alias, path)
	}
	out.WriteString(")\nfunc New() (*cobra.Command, error) {\nspec, err := api.GetSwagger(); if err != nil { return nil, err };\nreturn cliruntime.New(" + strconv.Quote(options.Name) + ", spec, map[string]cliruntime.Builder{\n")
	for i, op := range operations {
		fmt.Fprintf(&out, "%q: build%d,\n", op.Spec.OperationID, i)
	}
	out.WriteString("})\n}\n")
	for i, op := range operations {
		fmt.Fprintf(&out, "func build%d(server string, input cliruntime.Input) (*http.Request, error) {\n", i)
		arguments := []string{"server"}
		for index, p := range op.PathParams {
			expr, err := parser.ParseExpr(p.TypeDef())
			if err != nil {
				return nil, fmt.Errorf("path parameter type: %w", err)
			}
			var typed bytes.Buffer
			if err := format.Node(&typed, token.NewFileSet(), qualify(expr)); err != nil {
				return nil, err
			}
			name := fmt.Sprintf("path%d", index)
			fmt.Fprintf(&out, "var %s %s\nif err := input.Decode(\"path\", %q, &%s); err != nil { return nil, err }\n", name, typed.String(), p.ParamName, name)
			arguments = append(arguments, name)
		}
		parameters := append(append(append([]codegen.ParameterDefinition{}, op.QueryParams...), op.HeaderParams...), op.CookieParams...)
		if len(parameters) > 0 {
			fmt.Fprintf(&out, "var params api.%sParams\n", op.OperationId)
			used := map[string]bool{}
			for _, p := range parameters {
				field := p.GoName()
				if used[field] {
					return nil, fmt.Errorf("%s has parameters colliding in SDK Go field %s; set x-go-name on one parameter", op.Spec.OperationID, field)
				}
				used[field] = true
				fmt.Fprintf(&out, "if err := input.Decode(%q, %q, &params.%s); err != nil { return nil, err }\n", p.In, p.ParamName, field)
			}
			arguments = append(arguments, "&params")
		}
		function := "New" + op.OperationId + "Request"
		if len(op.Bodies) > 0 {
			function += "WithBody"
			arguments = append(arguments, "input.ContentType", "bytes.NewReader(input.Body)")
		}
		fmt.Fprintf(&out, "return api.%s(%s)\n}\n", function, strings.Join(arguments, ", "))
	}
	return imports.Process("commands.gen.go", []byte(out.String()), &imports.Options{Comments: true})
}
