// Package generator generates independent Cobra applications from OpenAPI.
package generator

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"net/http"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"sync"

	"github.com/araihu/oapi-cli-gen/internal/cliruntime"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"golang.org/x/mod/module"
	"golang.org/x/mod/semver"
)

const GoVersion = "1.27.3"
const OAPIVersion = "v2.8.1"

// Options describes one generated module. Paths are not embedded in its output.
type Options struct {
	Spec   string
	Name   string
	Module string
	// Requires pins additional modules used by explicit x-go-type-import extensions.
	Requires map[string]string
}

// Result is deterministic generated source plus the required module versions.
type Result struct {
	Files    map[string][]byte
	Module   string
	Requires map[string]string
	SpecHash string
}

// oapi-codegen maintains process-global naming/template state.
var codegenMu sync.Mutex
var commandName = regexp.MustCompile(`^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$`)

// Generate loads local references, validates the contract, and generates source.
// It never runs a shell, invokes Go or fetches remote OpenAPI documents.
func Generate(ctx context.Context, options Options) (*Result, error) {
	if !commandName.MatchString(options.Name) {
		return nil, errors.New("name must be a lowercase kebab-case command name")
	}
	if err := module.CheckPath(options.Module); err != nil {
		return nil, fmt.Errorf("invalid generated module path: %w", err)
	}
	doc, err := loadSpec(ctx, options.Spec)
	if err != nil {
		return nil, err
	}
	canonical, err := json.Marshal(doc)
	if err != nil {
		return nil, err
	}
	digest := sha256.Sum256(canonical)
	codegenMu.Lock()
	defer codegenMu.Unlock()
	version := OAPIVersion
	config := codegen.Configuration{PackageName: "api", Generate: codegen.GenerateOptions{Models: true, Client: true, EmbeddedSpec: true}, AllowRemoteRefsFrom: []string{}, NoVCSVersionOverride: &version}.UpdateDefaults()
	if err := config.Validate(); err != nil {
		return nil, err
	}
	sdk, err := codegen.Generate(doc, config)
	if err != nil {
		return nil, fmt.Errorf("oapi-codegen: %w", err)
	}
	definitions, err := codegen.OperationDefinitions(doc)
	if err != nil {
		return nil, err
	}
	builders := map[string]cliruntime.Builder{}
	for _, op := range definitions {
		builders[op.Spec.OperationID] = func(string, cliruntime.Input) (*http.Request, error) { return nil, nil }
	}
	if _, err := cliruntime.New(options.Name, doc, builders); err != nil {
		return nil, fmt.Errorf("CLI contract: %w", err)
	}
	parsed, err := parser.ParseFile(token.NewFileSet(), "client.gen.go", sdk, 0)
	if err != nil {
		return nil, err
	}
	versions := map[string]string{"github.com/spf13/cobra": "v1.10.2", "github.com/getkin/kin-openapi": "v0.152.0", "golang.org/x/text": "v0.43.0"}
	known := map[string]string{"github.com/oapi-codegen/runtime": "v1.8.0", "github.com/google/uuid": "v1.6.0", "github.com/oapi-codegen/nullable": "v1.2.0"}
	for path, version := range options.Requires {
		if err := module.Check(path, version); err != nil {
			return nil, fmt.Errorf("invalid extra module requirement: %w", err)
		}
		for _, floor := range []string{known[path], versions[path]} {
			if floor != "" && semver.Compare(version, floor) < 0 {
				return nil, fmt.Errorf("--require cannot downgrade %s below %s", path, floor)
			}
		}
		known[path] = version
	}
	for _, declaration := range parsed.Imports {
		path, _ := strconv.Unquote(declaration.Path.Value)
		if !strings.Contains(strings.Split(path, "/")[0], ".") {
			continue
		}
		if strings.HasPrefix(path, "github.com/getkin/kin-openapi/") {
			continue
		}
		matched := ""
		for candidate := range known {
			if (path == candidate || strings.HasPrefix(path, candidate+"/")) && len(candidate) > len(matched) {
				matched = candidate
			}
		}
		if matched == "" {
			return nil, fmt.Errorf("generated SDK imports %s; pin its module with --require module@version", path)
		}
		versions[matched] = known[matched]
	}
	commands, err := renderCommands(options, definitions, parsed.Imports)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{"internal/api/client.gen.go": []byte(sdk), "internal/cli/commands.gen.go": commands}
	entries, err := cliruntime.Sources.ReadDir(".")
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		data, err := cliruntime.Sources.ReadFile(entry.Name())
		if err != nil {
			return nil, err
		}
		files["internal/cliruntime/"+strings.TrimSuffix(entry.Name(), ".go")+".gen.go"] = append([]byte("// Code generated by oapi-cli-gen. DO NOT EDIT.\n\n"), data...)
	}
	mainSource := fmt.Sprintf(`// Code generated by oapi-cli-gen. DO NOT EDIT.
package main
import (
 "context"
 "fmt"
 "os"
 "os/signal"
 "syscall"
 %q
 %q
)
func main() {
 ctx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
 defer cancel()
 root, err := cli.New()
 if err == nil { err = root.ExecuteContext(ctx) }
 if err != nil { fmt.Fprintln(os.Stderr, err); os.Exit(cliruntime.ExitCode(err)) }
}
`, options.Module+"/internal/cli", options.Module+"/internal/cliruntime")
	files["cmd/"+options.Name+"/main.go"] = []byte(mainSource)
	for name, data := range files {
		formatted, err := format.Source(data)
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", name, err)
		}
		files[name] = formatted
	}
	result := &Result{Files: files, Module: options.Module, Requires: versions, SpecHash: hex.EncodeToString(digest[:])}
	files["go.mod"] = renderModule(options.Module, versions)
	return result, nil
}

func renderModule(name string, versions map[string]string) []byte {
	var out strings.Builder
	fmt.Fprintf(&out, "module %s\n\ngo %s\n\nrequire (\n", name, GoVersion)
	paths := make([]string, 0, len(versions))
	for path := range versions {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	for _, path := range paths {
		fmt.Fprintf(&out, "\t%s %s\n", path, versions[path])
	}
	out.WriteString(")\n")
	return []byte(out.String())
}

// qualify changes local SDK type references into api.Type references.
func qualify(expr ast.Expr) ast.Expr {
	switch value := expr.(type) {
	case *ast.Ident:
		switch value.Name {
		case "any", "bool", "byte", "complex64", "complex128", "error", "float32", "float64", "int", "int8", "int16", "int32", "int64", "rune", "string", "uint", "uint8", "uint16", "uint32", "uint64", "uintptr":
			return expr
		}
		return &ast.SelectorExpr{X: ast.NewIdent("api"), Sel: ast.NewIdent(value.Name)}
	case *ast.StarExpr:
		value.X = qualify(value.X)
	case *ast.ArrayType:
		value.Elt = qualify(value.Elt)
	case *ast.MapType:
		value.Key = qualify(value.Key)
		value.Value = qualify(value.Value)
	case *ast.StructType:
		for _, field := range value.Fields.List {
			field.Type = qualify(field.Type)
		}
	case *ast.IndexExpr:
		value.X = qualify(value.X)
		value.Index = qualify(value.Index)
	case *ast.IndexListExpr:
		value.X = qualify(value.X)
		for i := range value.Indices {
			value.Indices[i] = qualify(value.Indices[i])
		}
	}
	return expr
}
